<?php
/**
 * Примеры использования CachedRepository и защиты от stampede.
 *
 * В реальном проекте это вызывается из компонента/контроллера.
 */

use Vendor\Shop\Repository\ProductRepository;
use Vendor\Shop\Cache\StampedeProtectedCache;

require $_SERVER['DOCUMENT_ROOT'] . '/bitrix/modules/main/include/prolog_before.php';

// ============================================================
// Сценарий 1: Детальная страница товара
// ============================================================

$repo = new ProductRepository();

// Первый запрос — идёт в БД, кешируется на 24 часа
$product = $repo->getById(123);

// Следующие 24 часа — берётся из кеша (~0.5мс вместо 50мс)
$product = $repo->getById(123);

// После вызова CIBlockElement::Update(123, ...) или
// ElementTable::update(123, ...) — тег iblock_element_123 сбрасывается,
// следующий запрос снова пойдёт в БД


// ============================================================
// Сценарий 2: Список товаров раздела с пагинацией
// ============================================================

// Кешируется с тегами: iblock_section_12 + все iblock_element_*
// При изменении ЛЮБОГО товара из списка — сбрасывается эта страница
$items = $repo->getBySection(12, page: 2, perPage: 20);


// ============================================================
// Сценарий 3: Защита от stampede на "вирусной" странице
// ============================================================

// Представь: статья попала на главную Яндекса,
// и в один момент 500 человек/сек запрашивают страницу.
// Кеш истёк → без защиты БД упадёт.

$cache = new StampedeProtectedCache();

$article = $cache->remember(
    cacheId: 'viral_article_42',
    cacheDir: '/articles',
    ttl: 300, // 5 минут
    producer: function () {
        // Тяжёлый запрос — выполнит только один процесс (с lock),
        // остальные получат stale-данные или подождут
        return [
            'title' => 'Viral Article',
            'views' => 1_000_000,
            // ...
        ];
    }
);


// ============================================================
// Сценарий 4: "Горячий" кеш с плавным обновлением (XFetch)
// ============================================================

// Для данных, которые не могут быть "протухшими" (цены, остатки),
// но пересчитывать их каждый раз дорого — используем XFetch.
// Кеш обновляется до истечения TTL, плавно и без всплесков нагрузки.

$products = $cache->rememberXFetch(
    cacheId: 'hot_products_today',
    cacheDir: '/shop/hot',
    ttl: 600,
    producer: fn() => fetchTopSellingProducts(),
    beta: 1.5 // более агрессивное обновление
);


// ============================================================
// Сценарий 5: Инвалидация вручную при импорте
// ============================================================

// После обмена с 1С — сбрасываем кеш изменённых товаров
foreach ($changedProductIds as $productId) {
    $repo->invalidate($productId);
}

// Или по тегу, если нужно сбросить всё связанное:
\Bitrix\Main\Application::getInstance()
    ->getTaggedCache()
    ->clearByTag('iblock_id_5'); // сбросит все кеши каталога #5


// ============================================================
// Сценарий 6: Отладка кеша
// ============================================================

// Проверить, есть ли кеш, без получения данных
