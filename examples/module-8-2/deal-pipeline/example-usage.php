 *    require_once $_SERVER['DOCUMENT_ROOT'] . '/local/php_interface/classes/DealManager.php';
 * 3. Открыть /admin/deals_example.php в браузере
 */

require($_SERVER["DOCUMENT_ROOT"] . "/bitrix/header.php");

use Local\Bitrix24\DealManager;

// URL входящего webhook
$webhookUrl = 'https://вашподомен.bitrix24.ru/rest/1/входящий_webhook_токен';

$manager = new DealManager($webhookUrl);

// ============================================================================
// ПРИМЕР 1: Создание сделки
// ============================================================================
echo '<h3>Пример 1: Создание сделки</h3>';

$dealId = $manager->createDeal([
    'TITLE' => 'Внедрение CRM системы',
    'TYPE_ID' => 'SALE',              // Тип: продажа
    'STAGE_ID' => 'NEW',              // Стадия: новая
    'OPPORTUNITY' => 250000,          // Сумма: 250,000 руб.
    'CURRENCY_ID' => 'RUB',
    'BEGINDATE' => date('Y-m-d'),     // Дата начала
    'CLOSEDATE' => date('Y-m-d', strtotime('+30 days')), // Закрытие через 30 дней
    'PROBABILITY' => 70,              // Вероятность: 70%
    'CONTACT_ID' => 123,              // ID контакта
    'COMPANY_ID' => 456,              // ID компании
    'ASSIGNED_BY_ID' => 1,            // Ответственный
    'COMMENTS' => 'Клиент заинтересован в быстром внедрении'
]);

if ($dealId) {
    echo "✅ Сделка создана с ID: $dealId\n";
} else {
    echo "❌ Ошибка при создании сделки\n";
}

// ============================================================================
// ПРИМЕР 2: Получение информации о сделке
// ============================================================================
echo '<h3>Пример 2: Получение сделки</h3>';

if ($dealId) {
    $deal = $manager->getDeal($dealId);

    if ($deal) {
        echo "ID: {$deal['ID']}\n";
        echo "Название: {$deal['TITLE']}\n";
        echo "Стадия: {$deal['STAGE_ID']}\n";
        echo "Сумма: {$deal['OPPORTUNITY']} {$deal['CURRENCY_ID']}\n";
        echo "Вероятность: {$deal['PROBABILITY']}%\n";
        echo "Дата создания: {$deal['DATE_CREATE']}\n";
    }
}

// ============================================================================
// ПРИМЕР 3: Обновление сделки
// ============================================================================
echo '<h3>Пример 3: Обновление сделки</h3>';

if ($dealId) {
    $updated = $manager->updateDeal($dealId, [
        'STAGE_ID' => 'PREPARATION',    // Подготовка предложения
        'PROBABILITY' => 80,             // Повысили вероятность
        'COMMENTS' => 'Клиент согласовал бюджет, готовим договор'
    ]);

    if ($updated) {
        echo "✅ Сделка обновлена\n";
    }
}

// ============================================================================
// ПРИМЕР 4: Перемещение по воронке
// ============================================================================
echo '<h3>Пример 4: Перемещение на следующую стадию</h3>';

if ($dealId) {
    $newStage = $manager->moveToNextStage($dealId);

    if ($newStage) {
        echo "✅ Сделка перемещена на стадию: $newStage\n";
    } else {
        echo "❌ Не удалось переместить (уже на последней стадии?)\n";
    }
}

// ============================================================================
// ПРИМЕР 5: Получение стадий воронки
// ============================================================================
echo '<h3>Пример 5: Список стадий воронки</h3>';

$stages = $manager->getStages();

echo "Стадии воронки продаж:\n";
foreach ($stages as $stage) {
    echo "- {$stage['STATUS_ID']}: {$stage['NAME']}\n";
}

// ============================================================================
// ПРИМЕР 6: Привязка контактов
// ============================================================================
echo '<h3>Пример 6: Добавление контактов к сделке</h3>';

if ($dealId) {
    // Основной контакт
    $manager->addContact($dealId, 123, true);

    // Дополнительные контакты
    $manager->addContact($dealId, 456, false);
    $manager->addContact($dealId, 789, false);

    echo "✅ Контакты привязаны к сделке\n";

    // Получить список контактов
    $contacts = $manager->getContacts($dealId);
    echo "Всего контактов в сделке: " . count($contacts) . "\n";
}

// ============================================================================
// ПРИМЕР 7: Поиск сделок
// ============================================================================
echo '<h3>Пример 7: Поиск активных сделок</h3>';

$activeDeals = $manager->listDeals(
    [
        'CLOSED' => 'N',                 // Не закрытые
        '>OPPORTUNITY' => 100000,        // Сумма > 100,000
        'ASSIGNED_BY_ID' => 1            // Ответственный
    ],
    ['ID', 'TITLE', 'STAGE_ID', 'OPPORTUNITY'],
    ['OPPORTUNITY' => 'DESC']            // Сортировка по сумме
);

echo "Найдено активных сделок: " . count($activeDeals) . "\n";

foreach ($activeDeals as $deal) {
    echo "- #{$deal['ID']}: {$deal['TITLE']} - {$deal['OPPORTUNITY']} руб.\n";
}

// ============================================================================
// ПРИМЕР 8: Статистика по воронке
// ============================================================================
echo '<h3>Пример 8: Статистика по воронке продаж</h3>';

$stats = $manager->getPipelineStats();

echo "Состояние воронки:\n";
foreach ($stats as $stat) {
    echo "- {$stat['stage_name']}: {$stat['deals_count']} сделок на сумму " .
         number_format($stat['total_amount'], 0, '.', ' ') . " руб.\n";
}

// Общая статистика
$totalDeals = array_sum(array_column($stats, 'deals_count'));
$totalAmount = array_sum(array_column($stats, 'total_amount'));

echo "\nИтого: $totalDeals сделок на " . number_format($totalAmount, 0, '.', ' ') . " руб.\n";

// ============================================================================
// ПРИМЕР 9: Закрытие сделки (выигранной)
// ============================================================================
