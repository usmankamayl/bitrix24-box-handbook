    }
}
*/

// ============================================================================
// ПРИМЕР 11: Сделки по компании
// ============================================================================
echo '<h3>Пример 11: Все сделки конкретной компании</h3>';

$companyDeals = $manager->listDeals(
    ['COMPANY_ID' => 456],
    ['ID', 'TITLE', 'STAGE_ID', 'OPPORTUNITY', 'CLOSEDATE']
);

echo "Сделок компании #456: " . count($companyDeals) . "\n";

// ============================================================================
// ПРИМЕР 12: Сделки с истекающим сроком
// ============================================================================
echo '<h3>Пример 12: Сделки с истекающим сроком (неделя)</h3>';

$nextWeek = date('Y-m-d', strtotime('+7 days'));

$urgentDeals = $manager->listDeals(
    [
        'CLOSED' => 'N',
        '<=CLOSEDATE' => $nextWeek,
        '>=CLOSEDATE' => date('Y-m-d')
    ],
    ['ID', 'TITLE', 'CLOSEDATE', 'ASSIGNED_BY_ID']
);

echo "Срочных сделок: " . count($urgentDeals) . "\n";

foreach ($urgentDeals as $deal) {
    echo "- #{$deal['ID']}: {$deal['TITLE']} - закрыть до {$deal['CLOSEDATE']}\n";
}

require($_SERVER["DOCUMENT_ROOT"] . "/bitrix/footer.php");
?>
