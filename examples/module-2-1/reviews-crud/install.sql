CREATE TABLE IF NOT EXISTS `custom_reviews` (
    `ID` INT(11) NOT NULL AUTO_INCREMENT,
    `PRODUCT_ID` INT(11) NOT NULL COMMENT 'ID товара',
    `USER_ID` INT(11) NOT NULL COMMENT 'ID пользователя',
    `AUTHOR_NAME` VARCHAR(255) DEFAULT NULL COMMENT 'Имя автора (для гостей)',
    `AUTHOR_EMAIL` VARCHAR(255) DEFAULT NULL COMMENT 'Email автора (для гостей)',
    `RATING` TINYINT(1) NOT NULL COMMENT 'Рейтинг от 1 до 5',
    `REVIEW_TEXT` TEXT NOT NULL COMMENT 'Текст отзыва',
    `ADVANTAGES` TEXT DEFAULT NULL COMMENT 'Достоинства',
    `DISADVANTAGES` TEXT DEFAULT NULL COMMENT 'Недостатки',
    `ACTIVE` CHAR(1) NOT NULL DEFAULT 'N' COMMENT 'Активность (Y/N)',
    `DATE_CREATE` DATETIME NOT NULL COMMENT 'Дата создания',
    `DATE_MODERATED` DATETIME DEFAULT NULL COMMENT 'Дата модерации',
    `MODERATED_BY` INT(11) DEFAULT NULL COMMENT 'ID модератора',
    `LIKES_COUNT` INT(11) NOT NULL DEFAULT 0 COMMENT 'Количество лайков',
    `DISLIKES_COUNT` INT(11) NOT NULL DEFAULT 0 COMMENT 'Количество дизлайков',
    PRIMARY KEY (`ID`),
    INDEX `IX_PRODUCT_ID` (`PRODUCT_ID`),
    INDEX `IX_USER_ID` (`USER_ID`),
    INDEX `IX_ACTIVE` (`ACTIVE`),
    INDEX `IX_RATING` (`RATING`),
    INDEX `IX_DATE_CREATE` (`DATE_CREATE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Отзывы о товарах';
