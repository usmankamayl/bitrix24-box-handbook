CREATE TABLE IF NOT EXISTS `custom_orders` (
    `ID` INT(11) NOT NULL AUTO_INCREMENT,
    `ORDER_NUMBER` VARCHAR(50) NOT NULL COMMENT 'Номер заказа',
    `USER_ID` INT(11) NOT NULL COMMENT 'ID покупателя',
    `STATUS` ENUM('NEW', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED') NOT NULL DEFAULT 'NEW' COMMENT 'Статус заказа',
    `TOTAL_AMOUNT` DECIMAL(10,2) NOT NULL COMMENT 'Сумма заказа',
    `DISCOUNT_AMOUNT` DECIMAL(10,2) NOT NULL DEFAULT 0.00 COMMENT 'Сумма скидки',
    `FINAL_AMOUNT` DECIMAL(10,2) NOT NULL COMMENT 'Итоговая сумма',
    `PAYMENT_METHOD` VARCHAR(50) DEFAULT NULL COMMENT 'Способ оплаты',
    `IS_PAID` CHAR(1) NOT NULL DEFAULT 'N' COMMENT 'Оплачен (Y/N)',
    `DATE_CREATE` DATETIME NOT NULL COMMENT 'Дата создания',
    `DATE_PAID` DATETIME DEFAULT NULL COMMENT 'Дата оплаты',
    `DATE_DELIVERED` DATETIME DEFAULT NULL COMMENT 'Дата доставки',
    `DELIVERY_CITY` VARCHAR(100) DEFAULT NULL COMMENT 'Город доставки',
    `DELIVERY_REGION` VARCHAR(100) DEFAULT NULL COMMENT 'Регион',
    `SOURCE` VARCHAR(50) DEFAULT 'website' COMMENT 'Источник заказа',
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UX_ORDER_NUMBER` (`ORDER_NUMBER`),
    INDEX `IX_USER_ID` (`USER_ID`),
    INDEX `IX_STATUS` (`STATUS`),
    INDEX `IX_IS_PAID` (`IS_PAID`),
    INDEX `IX_DATE_CREATE` (`DATE_CREATE`),
    INDEX `IX_DELIVERY_CITY` (`DELIVERY_CITY`),
    INDEX `IX_SOURCE` (`SOURCE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Заказы для аналитики';
